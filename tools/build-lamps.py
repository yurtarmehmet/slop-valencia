"""Bake València's mapped street lamps into js/vlc-lamps.js (gap #9, street lights).

Sources (the only two with lamp positions; the Ajuntament publishes no street-lighting layer):
  - OpenStreetMap highway=street_lamp nodes (tools/data/vlc_street_lamps.json, from tools/lamps-extract.py), with
    their support / lamp_mount and height tags where mapped. © OpenStreetMap contributors, ODbL 1.0.
  - Ajuntament de València, *Mobiliari urbà* (dataset servicios-e-instalaciones, CC BY 4.0), elemento = FAROLA: the
    surveyed outline (1:500) of each lamp's base, partial (the Ciutat Vella core around the Plaça de l'Ajuntament and
    the Marina). The outline's perimeter tells a slim post (~1.4 m, a 0.45 m base) from a big candelabra base (>= 3 m).

Both are clipped to the detailed area (GEO.frame.detail). An OSM lamp within DEDUPE m of a surveyed Ajuntament lamp
is the same lamp and is dropped; so are exact repeats inside one source (< 0.3 m apart).

Output js/vlc-lamps.js: LAMPS, a flat [x, z, code, ...] Int32 list (x, z in decimetres of the world frame) with
  code = source * 16 + mount * 4 + size
  source 0 OSM, 1 Ajuntament; mount 0 untagged, 1 wall, 2 pole; size 0 unknown, 1 short (<= 5 m or a slim base),
  2 tall (>= 8 m) or a big base
and LAMP_COUNTS (raw, clipped, dropped) for tests/lamps.test.mjs. js/street-lamps.js picks each lamp's model by area
and fills the streets the data leaves dark by rule.

usage: python -I tools/build-lamps.py      (the GIS env: geopandas, shapely, pyproj)
"""
import json
import math
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'realism'))
import vlci  # noqa: E402

DEDUPE = 2.5
OUT = os.path.join(ROOT, 'js', 'vlc-lamps.js')


def inside(x, z):
    d = vlci.FRAME['detail']
    return d['x0'] <= x <= d['x1'] and d['z0'] <= z <= d['z1']


def main():
    osm = json.load(open(os.path.join(ROOT, 'tools', 'data', 'vlc_street_lamps.json')))
    g = vlci.add_world(vlci.read('servicios-e-instalaciones'))
    far = g[g['elemento'].astype(str).str.upper().str.strip() == 'FAROLA']
    aj_raw = len(far)
    far = vlci.clip_detail(far)
    lamps = []  # [x, z, source, mount, size, id]
    for _, r in far.iterrows():
        if math.isnan(r.x):
            continue
        per = float(r['st_length(']) if r.get('st_length(') is not None else 0
        lamps.append([r.x, r.z, 1, 2, 2 if per >= 3.0 else 1, int(r.objectid)])
    aj_clip = len(lamps)
    osm_clip = 0
    dup_osm = 0
    aj_pts = [(l[0], l[1]) for l in lamps]
    cell = {}
    for x, z in aj_pts:
        cell.setdefault((math.floor(x / 8), math.floor(z / 8)), []).append((x, z))

    def near_aj(x, z):
        cx, cz = math.floor(x / 8), math.floor(z / 8)
        for i in (cx - 1, cx, cx + 1):
            for j in (cz - 1, cz, cz + 1):
                for px, pz in cell.get((i, j), ()):
                    if (px - x) ** 2 + (pz - z) ** 2 < DEDUPE ** 2:
                        return True
        return False

    for lon, lat, oid, mount, height in osm:
        x, z = vlci.lonlat_to_world(lon, lat)
        if not inside(x, z):
            continue
        osm_clip += 1
        if near_aj(x, z):
            dup_osm += 1
            continue
        m = {'wall': 1, 'pole': 2}.get(mount, 0)
        s = 0 if not height else (1 if height <= 5 else (2 if height >= 8 else 0))
        lamps.append([x, z, 0, m, s, oid])
    # exact repeats inside a source
    seen = set()
    out = []
    repeats = 0
    for l in lamps:
        k = (l[2], round(l[0] / 0.3), round(l[1] / 0.3))
        if k in seen:
            repeats += 1
            continue
        seen.add(k)
        out.append(l)
    flat = []
    for x, z, src, m, s, _ in out:
        flat += [round(x * 10), round(z * 10), src * 16 + m * 4 + s]
    counts = {
        'osmRaw': len(osm), 'osmDetail': osm_clip, 'osmDuplicates': dup_osm,
        'ajuntamentRaw': aj_raw, 'ajuntamentDetail': aj_clip, 'repeats': repeats, 'baked': len(out)
    }
    src = (
        "// València's mapped street lamps, generated by tools/build-lamps.py (gap #9): OpenStreetMap street_lamp nodes\n"
        "// (© OpenStreetMap contributors, ODbL 1.0) and the Ajuntament de València's Mobiliari urbà, FAROLA\n"
        "// (servicios-e-instalaciones, CC BY 4.0), in the detailed area. Flat [x, z, code] triples, x & z in decimetres of the\n"
        "// world frame; code = source * 16 + mount * 4 + size (source 0 OSM / 1 Ajuntament; mount 0 untagged / 1 wall / 2 pole;\n"
        "// size 0 unknown / 1 short or slim base / 2 tall or big base). js/street-lamps.js picks the model by area.\n"
        f"export const LAMP_COUNTS = {json.dumps(counts)};\n"
        f"export const LAMPS = new Int32Array([{','.join(map(str, flat))}]);\n"
    )
    open(OUT, 'w').write(src)
    print(json.dumps(counts), f'-> {OUT} ({len(src)} bytes)')


if __name__ == '__main__':
    main()
