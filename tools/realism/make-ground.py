"""The metropolitan ground from the PNOA orthophoto (IGN WMTS pnoa-ma, CC BY 4.0 scne.es): z14 tiles (~7.4 m/px here)
over the OpenStreetMap extract's bounding box, mosaicked into js/vlc-ground.jpg, with its lon/lat bounds in
js/vlc-ground.js (boroughs.js drapes it over the land around the detailed city).

usage: python -I make-ground.py tile_cache_dir out_dir   (bbox from tools/data/bcn_coast.json)
"""
import json
import math
import os
import sys
import time
import urllib.request

from PIL import Image

cache, out = sys.argv[1:3]
os.makedirs(cache, exist_ok=True)
Z = 14
bbox = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'bcn_coast.json')))['bbox']  # lat0 lon0 lat1 lon1
UA = {'User-Agent': 'slop-valencia-ground/0.1 (hobby open-source project)'}
URL = ('https://www.ign.es/wmts/pnoa-ma?layer=OI.OrthoimageCoverage&style=default&tilematrixset=GoogleMapsCompatible'
       '&Service=WMTS&Request=GetTile&Version=1.0.0&Format=image/jpeg&TileMatrix={z}&TileCol={x}&TileRow={y}')


def tile_xy(lon, lat):
    n = 2 ** Z
    return (lon + 180) / 360 * n, (1 - math.log(math.tan(math.radians(lat)) + 1 / math.cos(math.radians(lat))) / math.pi) / 2 * n


def tile_lonlat(x, y):
    n = 2 ** Z
    return x / n * 360 - 180, math.degrees(math.atan(math.sinh(math.pi * (1 - 2 * y / n))))


x0, y0 = tile_xy(bbox[1], bbox[2])
x1, y1 = tile_xy(bbox[3], bbox[0])
tx0, ty0, tx1, ty1 = int(x0), int(y0), int(x1), int(y1)
W, H = (tx1 - tx0 + 1) * 256, (ty1 - ty0 + 1) * 256
mosaic = Image.new('RGB', (W, H))
for ty in range(ty0, ty1 + 1):
    for tx in range(tx0, tx1 + 1):
        path = os.path.join(cache, f'{Z}_{tx}_{ty}.jpg')
        if not os.path.exists(path):
            for attempt in range(4):
                try:
                    open(path, 'wb').write(urllib.request.urlopen(urllib.request.Request(URL.format(z=Z, x=tx, y=ty), headers=UA), timeout=30).read())
                    time.sleep(0.1)
                    break
                except Exception:
                    time.sleep(2 * (attempt + 1))
        mosaic.paste(Image.open(path).convert('RGB'), ((tx - tx0) * 256, (ty - ty0) * 256))
lonW, latN = tile_lonlat(tx0, ty0)
lonE, latS = tile_lonlat(tx1 + 1, ty1 + 1)
mosaic.save(os.path.join(out, 'vlc-ground.jpg'), quality=80, optimize=True, progressive=True)
bounds = {'width': W, 'height': H, 'lonW': lonW, 'lonE': lonE, 'latN': latN, 'latS': latS}
open(os.path.join(out, 'vlc-ground.js'), 'w').write(
    "// The metropolitan ground's orthophoto (js/vlc-ground.jpg), generated by tools/realism/make-ground.py.\n"
    "// PNOA cedido por © Instituto Geográfico Nacional (CC BY 4.0, scne.es): IGN WMTS pnoa-ma, z14 (~7.4 m/px).\n"
    "// A Web Mercator mosaic: lon/lat of its edges (rows linear in Mercator y; over this extent the lat error is under 3 m).\n"
    f"export const GROUND_PHOTO = {json.dumps(bounds)};\n")
print(f'{W}x{H} px, {os.path.getsize(os.path.join(out, "vlc-ground.jpg")) / 1e6:.2f} MB, lon {lonW:.4f}..{lonE:.4f} lat {latS:.4f}..{latN:.4f}')
