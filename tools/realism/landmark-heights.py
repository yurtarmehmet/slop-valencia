"""Each landmark footprint's height profile from PNOA-LiDAR 2023 (CC BY 4.0 scne.es): points inside the OpenStreetMap
outline (all classes but ground, noise & water), height above ground: p50, p90, p99.5 (the top), written to
js/vlc-landmark-heights.js for landmarks.js to size its models by.

usage: python -I landmark-heights.py landmarks.json lidar_dir out.js   (landmarks.json: LANDMARK_SITES + GEO.frame)
"""
import json
import math
import os
import sys

import numpy as np
import pdal
from pyproj import Transformer
from shapely.geometry import Polygon

src, lidar_dir, out = sys.argv[1:]
J = json.load(open(src))
fr = J['frame']
TH = math.radians(fr['bearingDeg'])
C, S = math.cos(TH), math.sin(TH)
to_utm = Transformer.from_crs(4326, 25830, always_xy=True)


def w2u(x, z):
    e = x * C - z * S
    n = -x * S - z * C
    return to_utm.transform(fr['lon0'] + e / fr['kx'], fr['lat0'] + n / fr['ky'])


res = {}
for name, s in J['sites'].items():
    ring = s.get('ring')
    if not ring:
        continue
    pts = [w2u(ring[i], ring[i + 1]) for i in range(0, len(ring), 2)]
    poly = Polygon(pts).buffer(0)
    if poly.is_empty or poly.area > 200000:
        continue
    cx, cy = poly.centroid.x, poly.centroid.y
    tile = os.path.join(lidar_dir, f'PNOA_2023_VAL_{int(cx // 1000)}-{int(cy // 1000) + 1}_H30_NPC02.laz')
    if not os.path.exists(tile):
        continue
    pipe = pdal.Pipeline(json.dumps({'pipeline': [tile, {'type': 'filters.crop', 'polygon': poly.wkt},
                                                  {'type': 'filters.hag_nn'}]}))
    try:
        pipe.execute()
    except Exception:
        continue
    a = pipe.arrays[0]
    m = ~np.isin(a['Classification'], [2, 7, 9, 18]) & (a['HeightAboveGround'] > 1.0)
    h = a['HeightAboveGround'][m]
    if h.size < 20:
        continue
    res[name] = {'p50': round(float(np.percentile(h, 50)), 1), 'p90': round(float(np.percentile(h, 90)), 1),
                 'top': round(float(np.percentile(h, 99.5)), 1), 'n': int(h.size)}
    print(f'{name:45s} p50 {res[name]["p50"]:6.1f}  p90 {res[name]["p90"]:6.1f}  top {res[name]["top"]:6.1f}  ({h.size} pts)')
# sites whose outline crop finds too few points (a tower inside the cathedral's outline): a radius round their centre
EXTRA = {'el Micalet': (-0.37570, 39.47530, 8)}
for name, (lon, lat, r) in EXTRA.items():
    x, y = to_utm.transform(lon, lat)
    tile = os.path.join(lidar_dir, f'PNOA_2023_VAL_{int(x // 1000)}-{int(y // 1000) + 1}_H30_NPC02.laz')
    pipe = pdal.Pipeline(json.dumps({'pipeline': [tile, {'type': 'filters.crop', 'point': f'POINT({x} {y})', 'distance': r},
                                                  {'type': 'filters.hag_nn'}]}))
    pipe.execute()
    a = pipe.arrays[0]
    h = a['HeightAboveGround'][~np.isin(a['Classification'], [2, 7, 9, 18]) & (a['HeightAboveGround'] > 1.0)]
    res[name] = {'p50': round(float(np.percentile(h, 50)), 1), 'p90': round(float(np.percentile(h, 90)), 1),
                 'top': round(float(np.percentile(h, 99.5)), 1), 'n': int(h.size)}
    print(f'{name:45s} p50 {res[name]["p50"]:6.1f}  p90 {res[name]["p90"]:6.1f}  top {res[name]["top"]:6.1f}  (radius {r} m)')
# keep the LANDMARK_SHAPES block landmark-shapes.py writes into the same module
keep = ''
if os.path.exists(out):
    old = open(out).read()
    i = old.find('// LANDMARK_SHAPES')
    keep = old[i:] if i >= 0 else ''
open(out, 'w').write('// Landmark heights above ground from PNOA-LiDAR 2023 (LiDAR-PNOA-cob3 2022-2025 CC-BY 4.0 scne.es), metres:\n'
                     '// p50 / p90 / top (99.5th percentile) of the points inside each OpenStreetMap outline.\n'
                     '// Generated by tools/realism/landmark-heights.py.\n'
                     f'export const LANDMARK_HEIGHTS = {json.dumps(res, ensure_ascii=False)};\n' + keep)
