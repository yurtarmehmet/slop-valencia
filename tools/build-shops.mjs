// Turns tools/data/vlc_shops.json & vlc_bus_lines.json (tools/shops-extract.py, © OpenStreetMap contributors, ODbL 1.0)
// into js/vlc-shops.js: every shop point in world metres with its trade, and the EMT line / destination pairs the bus
// signs show.
//
// usage: node tools/build-shops.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { lonLatToWorld } from '../js/city-config.js';
import { SHOP_KINDS } from '../js/shop-signs-kinds.js';

const root = new URL('../', import.meta.url);
const shops = JSON.parse(readFileSync(new URL('tools/data/vlc_shops.json', root)));
const lines = JSON.parse(readFileSync(new URL('tools/data/vlc_bus_lines.json', root)));
const kindIndex = new Map(SHOP_KINDS.map((k, i) => [k.key, i]));

// 6-byte records: i16 x, i16 z (world, 0.25 m units), u8 kind (SHOP_KINDS index), u8 variant hash (from the OSM id, so a
// shop keeps its wording between builds)
const out = [];
const missing = new Set();
for (const [lon, lat, kind, id] of shops) {
  const k = kindIndex.get(kind);
  if (k === undefined) {
    missing.add(kind);
    continue;
  }
  const { x, z } = lonLatToWorld(lon, lat);
  if (Math.abs(x) > 8000 || Math.abs(z) > 8000) continue;
  const h = Math.imul(Math.abs(id) ^ 0x9e3779b9, 0x85ebca6b) >>> 24;
  out.push([Math.round(x * 4), Math.round(z * 4), k, h]);
}
if (missing.size) throw new Error(`no SHOP_KINDS entry for ${[...missing].join(', ')}`);
const buf = Buffer.alloc(out.length * 6);
out.forEach(([x, z, k, h], i) => {
  buf.writeInt16LE(x, i * 6);
  buf.writeInt16LE(z, i * 6 + 2);
  buf.writeUInt8(k, i * 6 + 4);
  buf.writeUInt8(h, i * 6 + 5);
});

const js = `// València's shops, bars & restaurants and the EMT bus lines, generated by tools/build-shops.mjs from OpenStreetMap
// (tools/shops-extract.py; © OpenStreetMap contributors, ODbL 1.0). Only each shop's trade is kept (SHOP_KINDS in
// shop-signs-kinds.js), never its name. SHOP_DATA: base64 of 6-byte records [i16 x, i16 z (world, 0.25 m units),
// u8 kind, u8 variant hash].
export const SHOP_COUNT = ${out.length};
export const SHOP_DATA = '${buf.toString('base64')}';
// [line, destination] for each direction of the regular EMT lines
export const BUS_LINES = ${JSON.stringify(lines)};
`;
writeFileSync(new URL('js/vlc-shops.js', root), js);
console.log(`${out.length} shops, ${lines.length} bus directions, ${(js.length / 1024).toFixed(0)} KB`);
